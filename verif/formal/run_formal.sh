#!/bin/bash
# Run SymbiYosys tasks of the formal jobs in parallel; write verif/reports/formal_summary[_prefix].md.
# usage: run_formal.sh [--prefix] [--jobs "j1 j2"] [--tasks "t1 t2"] [-j N]
HERE=$(cd "$(dirname "$0")" && pwd); ROOT=$(cd $HERE/../.. && pwd)
export ABC=$ROOT/verif/scripts/abc_wrap.sh
TAG=fixed; RRARGS=""; JOBS=""; TASKS=""; NP=12
while [ $# -gt 0 ]; do case $1 in --prefix) TAG=prefix; RRARGS="--rtl-root $ROOT/build/verif/rtl_prefix --tag prefix";; --jobs) JOBS=$2; shift;; --tasks) TASKS=$2; shift;; -j) NP=$2; shift;; esac; shift; done
python3 $HERE/gen_jobs.py ${RRARGS:---tag fixed} >/dev/null || exit 1
B=$ROOT/build/verif/formal/$TAG
[ -z "$JOBS" ] && JOBS=$(ls $B)
list=$(mktemp)
for j in $JOBS; do while read job task mode depth expect note; do [ "${job:0:1}" = "#" ] && continue; [ -n "$TASKS" ] && ! echo " $TASKS " | grep -q " $task " && continue; echo "$j $task $mode $depth $expect $note"; done < $B/$j/tasks.txt; done > $list
ALL=$(mktemp); for j in $(ls $B); do while read job task mode depth expect note; do [ "${job:0:1}" = "#" ] && continue; echo "$job $task $mode $depth $expect $note"; done < $B/$j/tasks.txt; done > $ALL
runone() { j=$1; t=$2; B=$3; cd $B/$j; rm -rf ${j}_$t; s=$(date +%s); timeout ${SBY_TIMEOUT:-3600} sby -f ${j}.sby $t >/dev/null 2>&1; echo $? > ${j}_$t.rc; [ -f ${j}_$t/status ] || { rm -rf ${j}_$t; timeout ${SBY_TIMEOUT:-3600} sby -f ${j}.sby $t >/dev/null 2>&1; }; echo $(( $(date +%s) - s )) > ${j}_$t.sec; }
export -f runone
awk '{print $1, $2}' $list | xargs -P $NP -L1 bash -c 'runone $0 $1 '$B
OUT=$ROOT/verif/reports/formal_summary$([ $TAG = prefix ] && echo _prefix).md; mkdir -p $ROOT/verif/reports
{ echo "# Formal summary ($TAG RTL), SymbiYosys; generated by run_formal.sh $(date -I)"; echo; echo "| job | task | proof type | depth | expected | result | covers | sec |"; echo "|---|---|---|---|---|---|---|---|"
while read j t mode depth expect note; do
  d=$B/$j/${j}_$t; st=$(cat $d/status 2>/dev/null | head -1 | awk '{print $1}'); [ -z "$st" ] && st=NORUN
  case $mode in bmc) ty="BMC(bounded)";; prove) ty="induction/PDR";; cover) ty="cover";; esac
  if [ "$mode" = prove ] && [ "$st" = PASS ]; then ty="PROVEN (unbounded)"; fi
  cov="-"; if [ "$mode" = cover ]; then un=$(grep -c "Unreached cover" $d/logfile.txt 2>/dev/null); re=$(grep -c "Reached cover statement" $d/logfile.txt 2>/dev/null); cov="$re reached / $un unreached"; fi
  verdict=$st
  case $expect in PASS) [ "$st" = PASS ] && { [ "$mode" != cover ] || [ "$un" = 0 ]; } && ok=OK || ok=BAD;; FAIL) [ "$st" = FAIL ] && ok=OK || ok=BAD;; ANY) ok=info;; esac
  echo "| $j | $t | $ty | $depth | $expect | $st ($ok) | $cov | $(cat ${d}.sec 2>/dev/null) |"
done < $ALL; } > $OUT
cat $OUT; rm -f $list $ALL

// Testbench for I-16: drives the post-synthesis netlist of cofr_coproc_inter with
// realistic traffic so xsim can record switching activity into a SAIF.
//
// Realistic matters here. Vivado's vectorless estimate assumes a default toggle
// rate on every internal node, and this design's activity is nothing like
// uniform: the interleaved scan issues one FMA every cycle while the coefficient
// crossbar only changes once per wave. Feeding measured activity is the whole
// point -- see docs/POWER.md.
//
// Stimulus is fp32 ladder coefficients in the |a| ~ 1.5 regime the RTL tests use,
// generated by workloads/gen_power_stimulus.py. Batches run back to back with no
// idle gap, so this is a *busy* power figure, not an average-with-idle one.

`timescale 1ns/1ps

module tb_coproc_power;
    parameter W      = 32;
    parameter WIDTH  = 48;
    parameter DEPTH  = 7;
    parameter NBATCH = 24;

    reg  clock = 1'b0;
    reg  nReset = 1'b0;
    reg  start = 1'b0;
    wire busy, done;
    reg  [WIDTH*DEPTH*W-1:0] a_all;
    wire [WIDTH*W-1:0]       z;

    cofr_coproc_inter dut (
        .clock(clock), .nReset(nReset), .start(start),
        .busy(busy), .done(done),
        .a_all(a_all), .b_all({WIDTH*DEPTH*W{1'b0}}), .z(z)
    );

    always #5 clock = ~clock;                 // 10 ns -> 100 MHz

    reg [31:0] amem [0:WIDTH*DEPTH*NBATCH-1];
    integer b, j, k, guard;

    initial begin
        $readmemh("stimulus.mem", amem);
        a_all = {WIDTH*DEPTH*W{1'b0}};
        repeat (8) @(posedge clock);
        nReset = 1'b1;
        repeat (4) @(posedge clock);

        for (b = 0; b < NBATCH; b = b + 1) begin
            for (j = 0; j < WIDTH; j = j + 1)
                for (k = 0; k < DEPTH; k = k + 1)
                    a_all[(j*DEPTH + k)*W +: W] = amem[b*WIDTH*DEPTH + j*DEPTH + k];
            @(posedge clock);
            start = 1'b1;
            @(posedge clock);
            start = 1'b0;
            guard = 0;
            while (done !== 1'b1) begin
                @(posedge clock);
                guard = guard + 1;
                if (guard > 20000) begin
                    $display("TB ERROR: no done on batch %0d", b);
                    $finish;
                end
            end
            $display("batch %0d done after %0d cycles, z[0]=%h", b, guard, z[31:0]);
        end
        repeat (10) @(posedge clock);
        $display("TB_DONE %0d batches", NBATCH);
        $finish;
    end
endmodule
